async function старт() {
  показатьВерсию();
  эл.корень = $("cfg3d");
  if (!эл.корень) return;
  эл.хост = $("c3d-canvas");
  эл.сценаБлок = $("stage3d");
  эл.бейдж = $("c3d-badge");
  эл.итог = $("c3d-sum");
  эл.таблица = $("c3d-tbl");
  эл.подпись = $("c3d-note");
  эл.фасады = $("c3d-fac");
  эл.покраска = $("c3d-paint");
  эл.столешницы = $("c3d-top");
  эл.фартук = $("c3d-фартук");
  эл.цветФартука = $("c3d-фартук-цвет");
  эл.техника = $("c3d-opt");
  эл.длина = $("c3d-len");
  эл.длинаПодпись = $("c3d-len-val");
  эл.заявка = $("c3d-cta");
  эл.статус = $("c3d-status");
  эл.запасной = $("c3d-fallback");
  эл.запаснаяПодпись = $("c3d-fallback-text");
  эл.сообщение = $("c3d-msg");
  эл.кнопкаУправления = $("c3d-enable");
  эл.добавить = $("c3d-add");
  эл.список = $("c3d-list");
  эл.подсказка = $("c3d-list-tip");
  эл.карточка = $("c3d-card");

  try {
    конфиг = await (await fetch(КОНФИГ_АДРЕС, { cache: "no-store" })).json();
  } catch (е) {
    конфиг = { фасады: [], столешницы: [], техника: [], длина: { мин: 2, макс: 5, шаг: 0.1 }, старт: {}, кнопка: {} };
    сообщение("Не загрузились настройки конструктора", "ошибка");
    показать2Д("Настройки конструктора не загрузились — показываем схему.");
    return;
  }
  if (!(конфиг.фасады || []).length) {
    показать2Д("Настройки конструктора пусты — показываем схему.");
    return;
  }

  состояние = начальное();
  // техника: ключи для всех элементов панели (старые сохранения знали 2)
  состояние.техника = { hob: false, oven: false, pmm: false, fridge: false,
                        sink: false, faucet: false, ...(состояние.техника || {}) };
  const сохр = читатьСостав();
  if (сохр && сохр.состав) {
    состояние.состав = сохр.состав;
    состояние.форма = сохр.форма || "прямая";
    состояние.сторона_угла = сохр.сторона_угла === "правая" ? "правая" : "левая";
  }
  // справочник «что можно добавить» — с сервера, без цен. НЕ блокирует старт:
  // 3D и цена должны подняться даже если каталог не ответил (кнопки появятся позже)
  fetch(API, {
    method: "POST", headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ каталог: true }),
  }).then((о) => о.json()).then((д) => {
    if (!д || !д.ok || !(д.модули || []).length) return;
    каталог = д;
    построитьКнопкиДобавления();
    построитьСборку();
  }).catch((е) => console.warn("[k3d] каталог модулей не загрузился", е));

  построитьПанели();
  построитьКнопкиДобавления();
  подписатьУправление();
  наблюдатель();
  запросить();
}

старт().catch((е) => {
  console.error("[k3d] старт не удался", е);
  показать2Д("Конструктор не запустился — напишите нам, соберём вручную.");
});
