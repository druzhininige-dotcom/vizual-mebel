/* ── расстановка: свободное место, привязка, проверки ────────────────────── */
const ШАГ = 50;                     // шаг полей и кнопок, мм (ТЗ)
const ПРИТЯЖЕНИЕ = 40;              // радиус магнита, мм

function плечи() {
  return состояние.форма === "угол" ? ["задняя", "левая", "правая"] : ["задняя"];
}

function занятоДо(ряд, плечо) {
  let к = 0;
  for (const м of состояние.состав || []) {
    if ((м.ряд || "низ") !== ряд) continue;
    if ((м.плечо || "задняя") !== плечо) continue;
    к = Math.max(к, Number(м.x || 0) + Number(м.ширина || 0));
  }
  return к;
}

/* ── УГОЛ: сколько от угла уже занято соседним плечом ────────────────────
   Задний модуль, стоящий вплотную к углу, занимает не только свою ширину по X,
   но и глубину по другой стене (и наоборот). Без этого модуль, перенесённый на
   левую стену в x=0, встаёт В УГОЛ поверх заднего — ядро отвечает
   «накладываются: перекрытие 578 мм», и перенос молча не применяется. */
function уголЗанятДо(плечо, ряд, кромеИндекса) {
  const рядМ2 = (м) => ((м.ряд === "пенал") ? "низ" : (м.ряд || "низ"));
  const п_ = плечо || "задняя";
  const состав = состояние.состав || [];
  for (let i = 0; i < состав.length; i++) {
    if (i === кромеИндекса) continue;
    const м = состав[i];
    if (!м || м.тень) continue;
    if (рядМ2(м) !== ряд) continue;
    const чужое = (м.плечо || "задняя");
    // заднему плечу мешает ЛЮБОЕ боковое в углу; боковому — только задний
    if (п_ === "задняя") {
      if (чужое === "задняя") continue;
    } else if (чужое !== "задняя") {
      continue;
    }
    // угловая стоит В УГЛУ комнаты: слева x≈0, справа x≈стена−ширина.
    // В углу модуль занимает свою ШИРИНУ вдоль стены — и по задней, и крылом по
    // боковому плечу. Глубина корпуса (578/318) здесь не годится: модуль на
    // боковом плече заезжал под угловую на 50 мм, сервер отвечал «перекрытие».
    const ш = Number(м.ширина || 0);
    const стена = Number(состояние.длина) || 0;
    const вУглу = Number(м.x || 0) <= 1 ||
                  (стена > 0 && Number(м.x || 0) + ш >= стена - 1);
    if (!вУглу) continue;                                // не в углу — не мешает
    return ш || ((м.ряд === "верх") ? 318 : 578);
  }
  return 0;
}

/* «первое свободное место» — только для НОВОГО модуля.
   Список передаётся явно: при добавлении модуль ещё не в состоянии.
   Ищем не только конец ряда: в ряду бывают проёмы (модуль убрали, соседи
   раздвинуты, ряд собран не встык) — новый модуль обязан встать в ПЕРВЫЙ
   проём, куда влезает, а не за конец ряда. Если проёма нет — отдаём конец
   ряда с пометкой «нетМеста»: решение (удлинить стену или отказать) принимает
   добавитьМодуль. */
function свободноеМесто(ряд, ширина, плечо, списокВход, кромеИндекса) {
  const состав = Array.isArray(списокВход) ? списокВход : (состояние.состав || []);
  const рядМ2 = (м) => ((м.ряд === "пенал") ? "низ" : (м.ряд || "низ"));
  const угол = уголЗанятДо(плечо || "задняя", ряд, кромеИндекса);
  const отрезки = (п) => {
    const из = состав
      .filter((м) => рядМ2(м) === ряд && (м.плечо || "задняя") === п && !м.тень)
      .map((м) => [Number(м.x || 0), Number(м.x || 0) + Number(м.ширина || 0)]);
    if (угол > 0 && п === (плечо || "задняя")) из.push([0, угол]);   // угол занят
    return из.sort((а, б) => а[0] - б[0]);
  };
  const конец = (п) => отрезки(п).reduce((к, о) => Math.max(к, о[1]), 0);
  const стена = Number(состояние.длина) || 0;
  const список = плечо ? [плечо] : плечи();
  // 1) первый проём, в который влезает
  for (const п of список) {
    let курсор = 0;
    for (const [нач, кон2] of отрезки(п)) {
      if (нач - курсор >= ширина - 0.5) return { плечо: п, x: курсор };
      курсор = Math.max(курсор, кон2);
    }
    if (стена > 0 && курсор + ширина <= стена + 0.5) return { плечо: п, x: курсор };
  }
  // 2) ни в одну стену не влезает — конец первого плеча, пусть решает вызывающий
  const п = список[0];
  return { плечо: п, x: конец(п), нетМеста: true, занято: конец(п) };
}

/* прямоугольник модуля в мировых координатах — та же формула, что на сервере
   (сборка.py::габарит_модуля); три плеча: заднее, левое, правое */
function габарит(м) {
  const глуб = (м.ряд || "низ") === "верх" ? 300 : 560;
  const фасад = 18;
  const x = Number(м.x || 0), ш = Number(м.ширина || 0), отст = Number(м.y || 0);
  const плечо = м.плечо || "задняя";
  const стена = Number(состояние.длина) || 0;
  if (плечо === "задняя") {
    return { x0: x, x1: x + ш, z0: -(глуб + фасад) - отст, z1: -отст };
  }
  if (плечо === "правая") {
    // зеркало левого относительно правой стены (x = длина)
    return { x0: стена - (глуб + фасад) - отст, x1: стена - отст, z0: -x - ш, z1: -x };
  }
  return { x0: отст, x1: отст + глуб + фасад, z0: -x - ш, z1: -x };
}

function пересекается(а, б) {
  return а.x0 < б.x1 - 1 && а.x1 > б.x0 + 1 && а.z0 < б.z1 - 1 && а.z1 > б.z0 + 1;
}

/* допустима ли позиция: стена + пересечения в своём ряду и на своём плече */
function позицияГодна(индекс, x, z, плечо) {
  const м = состояние.состав[индекс];
  if (!м) return { ok: false, почему: "нет модуля" };
  const проба = {...м, x, z, плечо};
  const г = габарит(проба);
  const стена = Number(состояние.длина) || 0;
  const боковое = плечо === "левая" || плечо === "правая";
  if (г.x0 < -1) return { ok: false, почему: "за левой стеной" };
  if (г.x1 > стена + 1 && (плечо || "задняя") !== "правая") {
    return { ok: false, почему: "правее стены" };
  }
  if (г.z1 > 40) return { ok: false, почему: "за задней стеной" };
  if (г.z0 < -стена - 1 && боковое) {
    return { ok: false, почему: "дальше стены" };
  }
  for (let i = 0; i < состояние.состав.length; i++) {
    if (i === индекс) continue;
    const др = состояние.состав[i];
    if ((др.ряд || "низ") !== (м.ряд || "низ")) continue;
    if ((др.плечо || "задняя") !== (плечо || "задняя")) continue;
    if (пересекается(г, габарит(др))) return { ok: false, почему: "пересечение с соседом" };
  }
  return { ok: true };
}

/* пригоден ли ВЕСЬ состав: ни один модуль не за стеной и не пересекается
   с соседом своего ряда и своего плеча. Нужен после раздвижения ряда, когда
   проверка «по одному модулю» уже не описывает картину. */
function составГоден(список) {
  const стена = Number(состояние.длина) || 0;
  for (let i = 0; i < список.length; i++) {
    const а = список[i];
    if (!а || а.тень) continue;
    const г = габарит(а);
    const плечо = а.плечо || "задняя";
    if (г.x0 < -1) return { ok: false, почему: "за левой стеной" };
    if (г.z1 > 40) return { ok: false, почему: "за задней стеной" };
    if (плечо === "задняя" && стена > 0 && г.x1 > стена + 1) {
      return { ok: false, почему: "правее стены" };
    }
    if (плечо !== "задняя" && стена > 0 && г.z0 < -стена - 1) {
      return { ok: false, почему: "дальше стены" };
    }
    for (let j = i + 1; j < список.length; j++) {
      const б = список[j];
      if (!б || б.тень) continue;
      if ((а.ряд || "низ") !== (б.ряд || "низ")) continue;
      if ((а.плечо || "задняя") !== (б.плечо || "задняя")) continue;
      if (пересекается(г, габарит(б))) return { ok: false, почему: "пересечение с соседом" };
    }
  }
  return { ok: true };
}

/* привязка: стена, угол, сосед встык — если ближе ПРИТЯЖЕНИЕ.
   Второй параметр по оси глубины — Y ТЗ (от стены в комнату). */
function примагнитить(индекс, x, y, плечо) {
  let X = Math.round(x / ШАГ) * ШАГ;
  let Y = Math.round(y / ШАГ) * ШАГ;
  if (состояние.привязка === false) return { x: X, y: Math.max(0, Y) };
  const м = состояние.состав[индекс];
  if (!м) return { x: X, y: Math.max(0, Y) };
  const ш = Number(м.ширина || 0);
  const стена = Number(состояние.длина) || 0;
  // к стене и к углу
  for (const знач of [0]) {
    if (Math.abs(X - знач) < ПРИТЯЖЕНИЕ) X = знач;
    if (Math.abs(X + ш - знач) < ПРИТЯЖЕНИЕ) X = знач - ш;
    if (Math.abs(Y - знач) < ПРИТЯЖЕНИЕ) Y = знач;
  }
  // к правой стене (задний ряд выравнивается по x = длина)
  if (стена > 0 && (плечо || "задняя") === "задняя") {
    if (Math.abs(X + ш - стена) < ПРИТЯЖЕНИЕ) X = стена - ш;
  }
  // к соседям: левый край к правому краю соседа и наоборот
  for (const др of состояние.состав) {
    if (др === м) continue;
    if ((др.ряд || "низ") !== (м.ряд || "низ")) continue;
    if ((др.плечо || "задняя") !== (плечо || "задняя")) continue;
    const д_х = Number(др.x || 0), д_ш = Number(др.ширина || 0);
    if (Math.abs(X - (д_х + д_ш)) < ПРИТЯЖЕНИЕ) X = д_х + д_ш;
    if (Math.abs(X + ш - д_х) < ПРИТЯЖЕНИЕ) X = д_х - ш;
    if (Math.abs(Y - Number(др.y || 0)) < ПРИТЯЖЕНИЕ) Y = Number(др.y || 0);
  }
  return { x: X, y: Math.max(0, Y) };
}

let выбран = null;                  // индекс выбранного модуля

/* ── высота модуля (Z системы ТЗ): пределы и шаг 10 мм ──────────────────
   Низ верхнего шкафа не ниже поверхности столешницы + зазор фартука
   (850 + 38 + 550 = 1438, число приходит с сервера из правила.py), верх
   модуля не выше потолка. У напольных предел снизу — пол (0). */
const ШАГ_ВЫСОТЫ = 10;

function низВерхнегоМм() {
  const м = последние && последние.модель_для_3d;
  return Math.round(Number((м && м.низ_верхнего) || 1438));
}

function потолокМм() {
  const м = последние && последние.модель_для_3d;
  return Math.round(Number((м && м.потолок) || 2700));
}

function пределыВысоты(м) {
  const верх = (м.ряд || "низ") === "верх";
  const высота = Number(м.высота !== undefined && м.высота !== null
    ? м.высота : (верх ? низВерхнегоМм() : 0));
  // для модуля известна его собственная высота из каталога: верх не выше потолка
  const о = типПоКаталогу(м.тип) || {};
  const своя = Number((м.ряд === "верх" ? (о.высота || 720) : (о.высота || 850)));
  const низ = верх ? низВерхнегоМм() : 0;
  return { низ, верх: Math.max(низ, потолокМм() - своя), высота };
}

/* Сдвиг по Z на 10 мм. На границе — НЕ двигаем и молчим (кнопка неактивна),
   ошибок на экран не выводим: это не ошибка, а предел. */
function поднятьМодуль(индекс, знак) {
  const список = текущийСостав();
  const м = список[индекс];
  if (!м) return;
  if (!можноПоднимать(м)) return;      // напольный модуль стоит на полу
  const п = пределыВысоты(м);
  const новая = Math.round(п.высота + Number(знак) * ШАГ_ВЫСОТЫ);
  if (новая < п.низ - 0.5 || новая > п.верх + 0.5) { карточкаМодуля(); return; }
  список[индекс] = { ...м, высота: новая };
  состояние.состав = список;
  выбран = индекс;
  изменить({ состав: список });
  карточкаМодуля();
  построитьСборку();
}

function карточкаМодуля() {
  const блок = эл.карточка || $("c3d-card");
  if (!блок) return;
  if (выбран === null || !состояние.состав || !состояние.состав[выбран]) {
    блок.innerHTML = '<p class="c3d-tip">Кликните модуль в 3D или на плане — откроются поля X, Y и Z. ' +
      'Пустое место мышью — вращение камеры.</p>';
    return;
  }
  const м = состояние.состав[выбран];
  const о = типПоКаталогу(м.тип) || {};
  const имя = (о.название || м.тип) + " " + Math.round(м.ширина) + " мм";
  const верх = (м.ряд || "низ") === "верх";
  const п = пределыВысоты(м);
  const поZ = можноПоднимать(м);        // напольным высоту не меняем (шаг 3.1)
  const полеZ = поZ
    ? '<label>Z<input type="number" step="' + ШАГ_ВЫСОТЫ + '" data-карт="высота" value="' +
      Math.round(п.высота) + '"></label>'
    : '';
  const рядZ = поZ
    ? '<div class="c3d-card-b">' +
      '<button type="button" data-выше="-1"' +
      (п.высота - ШАГ_ВЫСОТЫ >= п.низ - 0.5 ? '' : ' disabled') + '>↓ Z</button>' +
      '<button type="button" data-выше="1"' +
      (п.высота + ШАГ_ВЫСОТЫ <= п.верх + 0.5 ? '' : ' disabled') + '>↑ Z</button>' +
      '<span class="c3d-tip">Z — шаг ' + ШАГ_ВЫСОТЫ + ' мм, ' + п.низ + '…' + п.верх + ' мм</span></div>'
    : '';
  блок.innerHTML =
    '<div class="c3d-card-h"><b>' + имя + '</b>' +
    '<button type="button" data-карт="убрать" title="Удалить">✕</button></div>' +
    '<div class="c3d-card-r">' +
    '<label>X<input type="number" step="' + ШАГ + '" data-карт="x" value="' +
    Math.round(Number(м.x || 0)) + '"></label>' +
    '<label>Y<input type="number" step="' + ШАГ + '" min="0" data-карт="y" value="' +
    Math.round(Number(м.y || 0)) + '"></label>' +
    полеZ +
    '</div>' +
    '<div class="c3d-card-b">' +
    '<button type="button" data-шаг="-1" data-ось="x">←</button>' +
    '<button type="button" data-шаг="1" data-ось="x">→</button>' +
    '<button type="button" data-шаг="-1" data-ось="y">↓</button>' +
    '<button type="button" data-шаг="1" data-ось="y">↑</button>' +
    '<span class="c3d-tip">X/Y — шаг ' + ШАГ + ' мм</span></div>' +
    рядZ +
    /* стена модуля — для ВСЕХ типов (ТЗ B.1 и C.2): ЗАД / ЛЕВ / ПРАВ.
       На прямой кухне боковых стен нет: выбор ЛЕВ/ПРАВ делает кухню Г-образной,
       о чём человек получает сообщение. */
    '<div class="c3d-card-b"><span class="c3d-tip">стена:</span>' +
    [["задняя", "ЗАД"], ["левая", "ЛЕВ"], ["правая", "ПРАВ"]].map(([ключ, текст]) =>
      '<button type="button" data-плечо="' + ключ + '"' +
      ((м.плечо || "задняя") === ключ ? ' class="on"' : '') + '>' + текст + '</button>').join("") +
    '</div>' +
    '<div class="c3d-card-b"><label class="c3d-tip"><input type="checkbox" data-карт="привязка"' +
    (состояние.привязка === false ? '' : ' checked') + '> привязка к соседу, стене, углу</label></div>' +
    '<p class="c3d-tip" id="c3d-card-msg"></p>';

  /* Отказ показываем ПОСЛЕ перерисовки карточки: раньше текст писали в старый
     элемент, карточкаМодуля() пересобирала разметку — и подсказка исчезала, то
     есть кнопка «не работала» без единого слова (жалоба 04.11 по стрелкам). */
  const отказВиден = (почему) => {
    карточкаМодуля();
    const э = $("c3d-card-msg");
    if (э) э.textContent = почему + " — вернул на прежнее место";
    сообщение(почему, "ошибка");
  };

  const перенести = (x, y, плечо, высота) => {
    const плечо2 = плечо || м.плечо || "задняя";
    const xy = примагнитить(выбран, x, y, плечо2);
    const сдвиг = подвинутьСоСдвигом(состояние.состав, выбран, xy.x, xy.y, плечо2);
    if (!сдвиг.ok) {
      отказВиден(сдвиг.почему);
      return;
    }
    const проверка = составГоден(сдвиг.состав);
    if (!проверка.ok) {
      отказВиден("нельзя: " + проверка.почему);
      return;
    }
    if (высота !== undefined) сдвиг.состав[выбран] = { ...сдвиг.состав[выбран], высота };
    состояние.состав = сдвиг.состав;
    изменить({ состав: сдвиг.состав });
    // Карточка держит СВОИ поля X/Y: без перерисовки следующее нажатие стрелки
    // считалось от старой координаты (второй шаг «не работал» или давал отказ).
    карточкаМодуля();
  };

  блок.querySelectorAll("[data-карт]").forEach((э) => {
    if (э.dataset.карт === "привязка") {
      э.onchange = () => {
        состояние.привязка = э.checked;
        запомнитьСостав();
      };
      return;
    }
    э.onchange = () => {
      const к = э.dataset.карт;
      if (к === "x") перенести(Number(э.value), Number(м.y || 0));
      else if (к === "y") перенести(Number(м.x || 0), Number(э.value));
      else if (к === "высота") {
        // предел тот же, что у кнопок: за границей значение возвращается
        const п2 = пределыВысоты(м);
        const з = Math.round(Number(э.value));
        if (з < п2.низ - 0.5 || з > п2.верх + 0.5) { карточкаМодуля(); return; }
        перенести(Number(м.x || 0), Number(м.y || 0), null, з);
      } else if (к === "убрать") убратьМодуль(выбран);
    };
  });
  блок.querySelectorAll("[data-шаг]").forEach((э) => {
    э.onclick = () => {
      const д = Number(э.dataset.шаг) * ШАГ;
      const ось = э.dataset.ось;
      // координаты берём из СОСТОЯНИЯ, а не из замыкания: карточка могла быть
      // построена до предыдущего шага (иначе шаг считается от старого x)
      const т = (состояние.состав || [])[выбран] || м;
      перенести(Number(т.x || 0) + (ось === "x" ? д : 0),
                Number(т.y || 0) + (ось === "y" ? д : 0));
    };
  });
  блок.querySelectorAll("[data-выше]").forEach((э) => {
    э.onclick = () => поднятьМодуль(выбран, Number(э.dataset.выше));
  });
  блок.querySelectorAll("[data-плечо]").forEach((э) => {
    э.onclick = () => перенестиНаСтену(выбран, э.dataset.плечо);
  });
}

/* ── перенос модуля на другую стену (ТЗ B) ────────────────────────────────
   Модуль встаёт в ПЕРВОЕ свободное место новой стены (проём или конец ряда).
   Не влезает — не переносим, показываем числа. На прямой кухне боковой стены
   нет: перенос на ЛЕВ/ПРАВ делает кухню Г-образной (угол — с этой стороны). */
function перенестиНаСтену(индекс, плечо) {
  const список = текущийСостав();
  const м = список[индекс];
  if (!м || !плечо) return;
  const было = м.плечо || "задняя";
  if (было === плечо) return;
  const ряд = (м.ряд === "пенал") ? "низ" : (м.ряд || "низ");
  const ширина = Number(м.ширина || 0);
  const боковая = плечо !== "задняя";
  if (боковая && состояние.форма !== "угол") {
    состояние.форма = "угол";
    состояние.сторона_угла = (плечо === "левая") ? "левая" : "правая";
    построитьКнопкиДобавления();
    сообщение("Кухня стала Г-образной: модуль перенесён на " +
              (плечо === "левая" ? "левую" : "правую") + " стену", "");
  }
  const место = свободноеМесто(ряд, ширина, плечо, список, индекс);
  if (место.нетМеста) {
    const занято = Math.round(место.занято || 0);
    if (занято + ширина > пределДлины()) {
      сообщение(`Не помещается: нужно ${Math.round(ширина)} мм, свободно ` +
                `${Math.max(0, пределДлины() - занято)} мм`, "ошибка");
      return;
    }
  }
  const новый = список.slice();
  новый[индекс] = { ...м, плечо, x: место.x, y: 0 };
  состояние.состав = новый;
  выбран = индекс;
  изменить({ длина: подогнатьДлину(новый), состав: новый });
  карточкаМодуля();
  построитьСборку();
}

/* ── «Отразить ряд» (ТЗ B.2) ──────────────────────────────────────────────
   Зеркало всей кухни: ЛЕВ ↔ ПРАВ, X' = длина_стены − X − ширина модуля.
   Двойное нажатие возвращает исходные координаты (проверяется тестом).
   Ширины не меняются, поэтому смета та же. */
function отразитьРяд() {
  const список = текущийСостав();
  if (!список.length) return;
  const стена = Number(состояние.длина) || 0;
  const итог = список.map((м) => {
    const плечо = м.плечо || "задняя";
    return {
      ...м,
      плечо: плечо === "левая" ? "правая" : (плечо === "правая" ? "левая" : "задняя"),
      x: Math.round(стена - Number(м.x || 0) - Number(м.ширина || 0)),
    };
  });
  const проверка = составГоден(итог);
  if (!проверка.ok) {
    сообщение("Отразить нельзя: " + проверка.почему, "ошибка");
    return;
  }
  состояние.состав = итог;
  if (состояние.форма === "угол") {
    состояние.сторона_угла = (сторонаУгла() === "левая") ? "правая" : "левая";
  }
  выбран = null;
  изменить({ состав: итог });
  построитьКнопкиДобавления();
  карточкаМодуля();
  построитьСборку();
  сообщение("Ряд отражён: ЛЕВ ↔ ПРАВ, координаты X зеркальны", "успех");
}

function построитьКнопкиДобавления() {
  if (!эл.добавить) return;
  эл.добавить.innerHTML = КНОПКИ_ДОБАВИТЬ
    .filter(([тип]) => типПоКаталогу(тип))
    .map(([тип, текст]) => `<button type="button" data-add="${тип}">${текст}</button>`).join("");
  эл.добавить.onclick = (е) => {
    const к = е.target.closest("[data-add]");
    if (к) добавитьМодуль(к.dataset.add);
  };
  for (const р of document.querySelectorAll('input[name="c3d-forma"]')) {
    р.checked = (р.value === (состояние.форма || "прямая"));
    р.onchange = () => сменитьФорму(р.value);
  }
  // «сторона угла»: видна только для Г-образной; меняет сторону, куда уходит
  // вторая ветка (влево или вправо от угла, в комнату)
  const сторона = document.createElement("label");
  сторона.id = "c3d-угол-блок";
  сторона.style.cssText = "display:inline-flex;gap:6px;align-items:center;" +
    "margin:0 8px 8px 0;font-size:13px;color:#9aa4b2";
  сторона.innerHTML = '<span>Угол:</span><select id="c3d-угол" ' +
    'aria-label="Сторона угла" style="padding:5px 8px;border-radius:8px;' +
    'border:1px solid #2a2f3a;background:#0f1115;color:#eef1f6">' +
    '<option value="левая">слева</option><option value="правая">справа</option></select>';
  const сел = сторона.querySelector("select");
  сел.value = сторонаУгла();
  сел.onchange = () => сменитьСторонуУгла(сел.value);
  сторона.style.display = состояние.форма === "угол" ? "" : "none";
  эл.добавить.prepend(сторона);

  // «Показать полки»: корпус становится полупрозрачным, полки остаются видны
  // (ТЗ 3d-bug7, пункт 3). Кнопка живёт здесь же, чтобы не править разметку.
  const полки = document.createElement("label");
  полки.id = "c3d-полки-блок";
  полки.style.cssText = "display:inline-flex;gap:6px;align-items:center;" +
    "margin:0 8px 8px 0;font-size:13px;color:#9aa4b2";
  полки.innerHTML = '<input type="checkbox" id="c3d-полки"> <span>Показать полки</span>';
  полки.querySelector("input").onchange = (е) => {
    if (сцена && сцена.показатьПолки) сцена.показатьПолки(е.target.checked);
  };
  эл.добавить.prepend(полки);

  // «Отразить ряд»: зеркало всей кухни ЛЕВ ↔ ПРАВ (ТЗ B.2).
  // Двойное нажатие возвращает исходные координаты.
  const отразить = document.createElement("button");
  отразить.type = "button";
  отразить.id = "c3d-отразить";
  отразить.textContent = "Отразить ряд";
  отразить.title = "Зеркало кухни: ЛЕВ ↔ ПРАВ, X = длина − X − ширина";
  отразить.style.cssText = "margin:0 8px 8px 0;padding:6px 10px;border-radius:8px;" +
    "border:1px solid #2a2f3a;background:#0f1115;color:#eef1f6;font-size:13px;cursor:pointer";
  отразить.onclick = () => отразитьРяд();
  эл.добавить.prepend(отразить);
}

function построитьСборку() {
  if (!эл.список) return;
  const м = (последние && последние.модель_для_3d) || {};
  const изСервера = Array.isArray(м.состав) ? м.состав : [];
  // показываем то, что человек реально видит: свою расстановку, иначе серверную
  const состав = (Array.isArray(состояние.состав) && состояние.состав.length)
    ? состояние.состав : изСервера;
  if (!состав.length) {
    эл.список.innerHTML = "";
    if (эл.подсказка) эл.подсказка.innerHTML =
      "Ряд собран автоматически по длине стены. Нажмите «+ …», чтобы собрать свою кухню.";
    return;
  }
  const рядМ = (м2) => ((м2.ряд === "пенал") ? "низ" : (м2.ряд || "низ"));
  const по = (ряд) => состав.map((м2, i) => ({ ...м2, i })).filter((м2) => рядМ(м2) === ряд);
  const чип = (м2) => {
    const о = типПоКаталогу(м2.тип);
    const ширины = (о && о.ширины) || [м2.ширина];
    const варианты = ширины.map((ш) => `<option value="${ш}"${Math.abs(ш - м2.ширина) < 0.5 ? " selected" : ""}>${Math.round(ш)}</option>`).join("");
    const имя = КОРОТКО[м2.тип] || (о && о.название) || м2.тип;
    const x = Math.round(Number(м2.x || 0)), y = Math.round(Number(м2.y || 0));
    const пZ = пределыВысоты(м2);
    const z = Math.round(пZ.высота);
    const на = м2.i === выбран ? ' class="c3d-chip on"' : ' class="c3d-chip"';
    const плечо = (состояние.форма === "угол")
      ? ` <i class="c3d-chip-плечо">${(м2.плечо || "задняя") === "левая" ? "лев"
          : (м2.плечо || "задняя") === "правая" ? "прав" : "зад"}</i>` : "";
    // ↑ / ↓ в списке — ПОРЯДОК модулей в своём ряду (ТЗ 04.11, пункт C).
    // Высота Z правится кнопками «↑ Z / ↓ Z» в карточке модуля.
    // Нижний и верхний ряды независимы: соседа ищем только среди модулей
    // того же ряда и того же плеча.
    const кнопкиПорядка =
      `<button type="button" data-раньше="${м2.i}" title="Выше в ряду" aria-label="Выше в ряду">↑</button>` +
      `<button type="button" data-позже="${м2.i}" title="Ниже в ряду" aria-label="Ниже в ряду">↓</button>`;
    // полки: 0–4, по умолчанию 1; выбор рядом с шириной модуля
    const полок = (м2.наполнение && м2.наполнение.полок !== undefined)
      ? Number(м2.наполнение.полок) : ПОЛОК_ПО_УМОЛЧАНИЮ;
    const выборПолок = ТИПЫ_С_ПОЛКАМИ.has(м2.тип)
      ? `<select data-полок="${м2.i}" aria-label="Полок 0–4" title="Полок в модуле">` +
        Array.from({length: ПОЛОК_МАКС + 1}, (_, н) =>
          `<option value="${н}"${н === полок ? " selected" : ""}>полок ${н}</option>`).join("") +
        `</select>`
      : "";
    return `<span${на} data-выбрать="${м2.i}" title="Кликните, чтобы выбрать модуль">
      <button type="button" class="c3d-chip-имя" data-выбрать="${м2.i}"><b>${имя}</b>${плечо}
        <i>X ${x} · Y ${y} · Z ${z}</i></button>
      <select data-ширина="${м2.i}" aria-label="Ширина модуля">${варианты}</select>
      ${выборПолок}
      <button type="button" data-влево="${м2.i}" title="Сдвинуть на ${ШАГ} мм влево" aria-label="Сдвинуть влево">←</button>
      <button type="button" data-вправо="${м2.i}" title="Сдвинуть на ${ШАГ} мм вправо" aria-label="Сдвинуть вправо">→</button>
      ${кнопкиПорядка}
      <button type="button" data-убрать="${м2.i}" title="Убрать модуль" aria-label="Убрать модуль">✕</button></span>`;
  };
  эл.список.innerHTML =
    `<div class="c3d-row"><span class="lbl">низ</span>${по("низ").map(чип).join("") || '<span class="c3d-tip">пусто</span>'}</div>` +
    `<div class="c3d-row"><span class="lbl">верх</span>${по("верх").map(чип).join("") || '<span class="c3d-tip">пусто</span>'}</div>`;
  эл.список.onclick = (е) => {
    const б = е.target.closest("button");
    const выб = е.target.closest("[data-выбрать]");
    if (!б) {
      // клик по фону чипа — тоже выбор модуля
      if (выб && выб.dataset.выбрать != null) {
        выбран = Number(выб.dataset.выбрать);
        карточкаМодуля();
        построитьСборку();
      }
      return;
    }
    if (б.dataset.влево != null) сдвинутьМодуль(Number(б.dataset.влево), -1);
    else if (б.dataset.вправо != null) сдвинутьМодуль(Number(б.dataset.вправо), 1);
    else if (б.dataset.раньше != null) переставитьМодуль(Number(б.dataset.раньше), -1);
    else if (б.dataset.позже != null) переставитьМодуль(Number(б.dataset.позже), 1);
    else if (б.dataset.выше != null) поднятьМодуль(Number(б.dataset.выше), 1);
    else if (б.dataset.ниже != null) поднятьМодуль(Number(б.dataset.ниже), -1);
    else if (б.dataset.убрать != null) убратьМодуль(Number(б.dataset.убрать));
    else if (б.dataset.выбрать != null) {
      выбран = Number(б.dataset.выбрать);
      карточкаМодуля();
      построитьСборку();
    }
  };
  эл.список.onchange = (е) => {
    const в = е.target.closest("select[data-ширина]");
    if (в) сменитьШирину(Number(в.dataset.ширина), в.value);
    const п = е.target.closest("select[data-полок]");
    if (п) изменитьПолки(Number(п.dataset.полок), Number(п.value));
  };
  if (эл.подсказка) {
    // «Свободно у стены» — по ЗАДНЕЙ стене (у неё известна длина). Модули
    // боковой ветки Г-образной в счёт не идут: их x отсчитывается вдоль
    // своего плеча, и в сумму по главной стене они попадать не должны.
    const стен = Math.round(Number(состояние.длина) || 0);
    const задЗанято = (ряд) => Math.round(Math.max(0, ...состав
      .filter((м2) => ((м2.ряд === "пенал") ? "низ" : (м2.ряд || "низ")) === ряд
                   && (м2.плечо || "задняя") === "задняя")
      .map((м2) => Number(м2.x || 0) + Number(м2.ширина || 0)), 0));
    const остаток = Math.max(0, стен - задЗанято("низ"));
    эл.подсказка.innerHTML = остаток >= 50
      ? `Свободно у стены: <b>${остаток} мм</b> — можно добавить модуль или увеличить ширину.`
      : "Ряд стоит встык: свободного места у стены нет. Порядок модулей — стрелками ↑ ↓.";
  }
}

