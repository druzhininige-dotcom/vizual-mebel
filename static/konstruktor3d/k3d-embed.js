/* id сцены («м1», «м2» …) → индекс в своём составе.
   Сервер нумерует модули по порядку отправленного массива, тени пропускаем. */
function индексПоId(id) {
  const мс = ((последние && последние.модель_для_3d && последние.модель_для_3d.модули) || [])
    .filter((м) => !м.тень);
  const номер = мс.findIndex((м) => м.id === id);
  if (номер < 0) return -1;
  const состав = состояние.состав || [];
  if (номер < состав.length) return номер;
  return -1;
}

/* Основа для правки: своя расстановка, а если её ещё нет — тот ряд, который
   сервер собрал по длине стены. Иначе первое «+ Тумба» затирало всю кухню. */
function текущийСостав() {
  if (Array.isArray(состояние.состав) && состояние.состав.length) return состояние.состав.slice();
  const м = (последние && последние.модель_для_3d) || {};
  // Модули сервера несут ПОЛНЫЕ координаты: x вдоль стены, y от стены в комнату,
  // z — низ модуля от пола. Пока здесь оставались только тип/ширина/ряд, любая
  // правка начинала ряд с нуля: новый модуль вставал в x=0 поверх первого
  // (пересечение → /calc отвечал ok:false и 3D «не менялось»), полки и плечо
  // терялись. Баг 04.11, пункты C/D.
  const модули = Array.isArray(м.модули) ? м.модули.filter((х) => !х.тень) : [];
  if (модули.length) {
    return модули.map((х) => ({
      тип: х.тип,
      ширина: Number(х.ширина),
      ряд: х.ряд || "низ",
      плечо: х.плечо || "задняя",
      x: Number(х.x || 0),
      y: Number(х.y || 0),
      высота: Number(х.z || 0),
      ...(х.наполнение && typeof х.наполнение === "object" ? { наполнение: { ...х.наполнение } } : {}),
      ...(Array.isArray(х.техника) && х.техника.length ? { техника: х.техника.slice() } : {}),
    }));
  }
  return (Array.isArray(м.состав) ? м.состав : []).map((х) => ({
    тип: х.тип, ширина: х.ширина, ряд: х.ряд, плечо: х.плечо || "задняя",
    ...(х.x === null || х.x === undefined ? {} : { x: Number(х.x) }),
    ...(х.z ? { высота: Number(х.z) } : {}),
  }));
}

/* Модули ставятся встык, поэтому ряд может перестать влезать в стену.
   Тогда удлиняем стену (ползунок «Длина кухни») — «+ Тумба» не должен
   упираться в отказ, человек просто хочет ещё одну тумбу. */
function подогнатьДлину(список) {
  // длина считается по КАЖДОМУ плечу отдельно: у Г-образной два плеча.
  // Место задаёт x, поэтому берём правый край модуля, а не сумму ширин.
  const до = (ряд, плечо) => список
    .filter((м) => (м.ряд || "низ") === ряд && (м.плечо || "задняя") === плечо)
    .reduce((а, м) => Math.max(а, Number(м.x || 0) + Number(м.ширина || 0)), 0);
  const плечи_ = [...new Set(список.map((м) => м.плечо || "задняя"))];
  let нужно = 0;
  for (const п of плечи_) {
    нужно = Math.max(нужно, до("низ", п), до("верх", п));
  }
  const максимум = Math.round(Number((конфиг.длина || {}).макс || 5) * 1000);
  const шаг = Math.round(Number((конфиг.длина || {}).шаг || 0.1) * 1000) || 100;
  if (нужно > состояние.длина) {
    return Math.min(максимум, Math.ceil(нужно / шаг) * шаг);
  }
  return состояние.длина;
}

/* Предел длины стены — не выдуманное число, а из настроек конструктора. */
function пределДлины() {
  return Math.round(Number((конфиг.длина || {}).макс || 5) * 1000);
}

/* Сколько модулей лишних в самом длинном ряду. Считаем формулой по ширинам:
   если ряд не влезает в стену, «убрать лишнее» снимает с КОНЦА самые узкие
   модули, пока ряд не станет короче стены. Возвращает {индексы, было, стало}. */
function лишниеВРяду(список, стена) {
  const по = (ряд) => список.map((м, i) => ({ м, i }))
    .filter((х) => (х.м.ряд || "низ") === ряд);
  const ряды = [...new Set(список.map((м) => м.ряд || "низ"))];
  let худший = null;
  for (const ряд of ряды) {
    const в = по(ряд);
    const было = в.reduce((а, х) => а + Number(х.м.ширина || 0), 0);
    if (было <= стена) continue;
    // снимаем с конца, начиная с самых узких: так остаётся больше модулей
    const порядок = [...в].sort((а, б) => (Number(а.м.ширина || 0) - Number(б.м.ширина || 0))
      || (б.i - а.i));
    let остаток = было;
    const снять = [];
    for (const х of порядок) {
      if (остаток <= стена) break;
      // не последний в ряду: если снять всё, не останется ничего
      if (снять.length >= в.length - 1) break;
      снять.push(х);
      остаток -= Number(х.м.ширина || 0);
    }
    if (!худший || было > худший.было) {
      худший = { индексы: снять.map((х) => х.i).sort((а, б) => б - а), было, стало: остаток, ряд };
    }
  }
  return худший;
}

/* Ряд перестал влезать в стену. Раньше это выглядело как «не собирается» и
   уводило на 2D-схему. Теперь: остаёмся в 3D, объясняем цифрами и даём кнопку. */
function рядНеВлезает(список, стена) {
  const мс = лишниеВРяду(список, стена);
  if (!мс) return false;
  const было = Math.round(мс.было), стало = Math.round(мс.стало), стен = Math.round(стена);
  const какой = мс.ряд === "верх" ? "Верхний ряд" : "Нижний ряд";
  const лш = (мм) => (мм / 1000).toFixed(2).replace(".", ",") + " м";
  const т = `3D включено, ряд не помещается: ${какой} ${лш(было)} при длине кухни ${лш(стен)}. ` +
    `Можно удлинить кухню ДО ${лш(пределДлины())} или убрать ${мс.индексы.length} ` +
    `модул${мс.индексы.length === 1 ? "ь" : "я"} — останется ${лш(стало)}.`;
  сообщение(t, "ошибка");
  показатьКнопкуЛишнего(мс.индексы, лш(стало), т);
  return true;
}

