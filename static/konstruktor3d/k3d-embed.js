/* ── формат денег: «168 000 ₽» / «цена уточняется» ────────────────────── */
function деньги(сумма) {
  if (сумма === null || сумма === undefined) return "цена уточняется";
  return String(Math.round(сумма)).replace(/\B(?=(\d{3})+(?!\d))/g, "\u00A0") + "\u00A0₽";
}

/* Итог. Решение владельца 04.11.2026: если у части позиций цены нет (техника,
   фартук до ответа Кости), показываем СУММУ ПО СТРОКАМ С ЦЕНОЙ и честный хвост
   «+ уточнить N поз.». Раньше в этом случае на экране стояло «уточняется» без
   чисел — человек не понимал порядок цены вообще. */
function итогПодпись(данные) {
  const без = (данные.без_цены || []).filter(Boolean);
  const хвост = без.length ? ` + уточнить ${без.length} поз.` : "";
  if (данные.итого !== null && данные.итого !== undefined) {
    return "≈ " + деньги(данные.итого) + хвост;
  }
  // итого_от — сумма по строкам, у которых цена ЕСТЬ (та же наценка и округление)
  if (данные.итого_от !== null && данные.итого_от !== undefined) {
    return "от " + деньги(данные.итого_от) + хвост;
  }
  return "уточняется";
}

function длинаСтрокой(мм) {
  return (Math.round(мм / 100) / 10).toFixed(1).replace(".", ",");
}

/* ── состояние: адрес → память → стартовые значения конфига ────────────── */
/* Состав с позициями: [{тип,ширина,ряд,плечо,x,z,высота}] → base64url.
   Кириллица в JSON, поэтому сначала encodeURIComponent → unescape → btoa. */
function упаковатьСостав(состав) {
  try {
    const json = JSON.stringify(состав);
    const utf = unescape(encodeURIComponent(json));
    return btoa(utf).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
  } catch (е) { return ""; }
}
function распаковатьСостав(строка) {
  try {
    const b = String(строка).replace(/-/g, "+").replace(/_/g, "/");
    const json = decodeURIComponent(escape(atob(b + "===".slice((b.length + 3) % 4))));
    const с = JSON.parse(json);
    return Array.isArray(с) && с.length ? с : null;
  } catch (е) { return null; }
}

function изСтроки(строка) {
  if (!строка) return null;
  const ч = String(строка).split("|");
  // v3: v3|фасад|столешница|длина|техника|покраска|форма|<состав base64>
  if (ч[0] === "v3" && ч.length >= 8) {
    const фасад3 = (конфиг.фасады || []).find((ф) => ф.id === ч[1]);
    const стол3 = (конфиг.столешницы || []).find((с) => с.id === ч[2]);
    const длина3 = Number(ч[3]);
    if (фасад3 && стол3 && isFinite(длина3)) {
      const техника3 = { hob: false, oven: false };
      for (const к of String(ч[4] || "").split(/[+\s]+/).filter(Boolean)) {
        if (к in техника3) техника3[к] = true;
      }
      return { фасад: фасад3.id, столешница: стол3.id, длина: предел(длина3),
               техника: техника3, покраска: типПокраскиИз(ч[5]),
               форма: ч[6] === "угол" ? "угол" : "прямая",
               // 9-е поле — сторона угла; старые ссылки его не знают → «слева»
               сторона_угла: ч[8] === "право" ? "правая" : "левая",
               // 10-е поле — фартук (ТЗ E). Нет поля → пусто → «старт» из конфига,
               // то есть «Без фартука»: старые ссылки открываются как раньше.
               фартук: ч[9] ? String(ч[9]).split("~")[0] : "",
               цвет_фартука: ч[9] ? (String(ч[9]).split("~")[1] || "") : "",
               состав: распаковатьСостав(ч[7]) };
    }
  }
  if (ч.length < 5 || ч[0] !== "v2") return null;
  const фасад = (конфиг.фасады || []).find((ф) => ф.id === ч[1]);
  const столешница = (конфиг.столешницы || []).find((с) => с.id === ч[2]);
  const длина = Number(ч[3]);
  if (!фасад || !столешница || !isFinite(длина)) return null;
  const техника = { hob: false, oven: false };
  // Старые ссылки вида ?k=v2|graphit|quartz|3300|hob+oven: «+» в query
  // URLSearchParams отдаёт ПРОБЕЛОМ («hob oven»), поэтому делим и по «+», и по
  // пробелу — иначе обе техники теряются молча (проверено 30.10.2026 тестом Л2).
  for (const к of String(ч[4] || "").split(/[+\s]+/).filter(Boolean)) if (к in техника) техника[к] = true;
  // 6-е поле — тип покраски. Старые ссылки (5 полей) читаются как раньше:
  // пусто → МАТОВАЯ (допущение: цена покраски по умолчанию — матовая).
  return { фасад: фасад.id, столешница: столешница.id, длина: предел(длина), техника,
           покраска: типПокраскиИз(ч[5]) };
}

function типПокраскиИз(значение) {
  const п = конфиг.покраска || {};
  const есть = (п.варианты || []).map((в) => в.id);
  const т = String(значение || "").trim();
  if (есть.indexOf(т) >= 0) return т;
  return п.старт && есть.indexOf(п.старт) >= 0 ? п.старт : (есть[0] || "");
}

function вСтроку(с) {
  const т = Object.keys(с.техника).filter((к) => с.техника[к]).join("+");
  const база = ["v3", с.фасад, с.столешница, Math.round(с.длина), т, типПокраскиИз(с.покраска),
                с.форма === "угол" ? "угол" : "прямая"];
  const состав = Array.isArray(с.состав) && с.состав.length ? с.состав : null;
  // без состава — пустое 8-е поле: ссылка остаётся короткой, типовой ряд соберётся по длине
  база.push(состав ? упаковатьСостав(состав) : "");
  // девятое поле — сторона угла. Пишем ВСЕГДА (для прямой это «лево»): иначе
  // десятое поле (фартук) съезжало бы на место стороны и ссылка читалась бы
  // по-разному. Старые 8-польные ссылки не трогаем — они короче.
  база.push(с.сторона_угла === "правая" ? "право" : "лево");
  // десятое поле — фартук: id и, у стекла, цвет через «~»
  const ф = (с.фартук && с.фартук !== "нет") ? String(с.фартук) : "";
  if (ф) база.push(с.цвет_фартука ? ф + "~" + с.цвет_фартука : ф);
  return база.join("|");
}

function предел(мм) {
  const д = конфиг.длина || { мин: 2, макс: 5, шаг: 0.1 };
  const шаг = Math.round((д.шаг || 0.1) * 1000);
  const мин = Math.round((д.мин || 2) * 1000);
  const макс = Math.round((д.макс || 5) * 1000);
  return Math.min(макс, Math.max(мин, Math.round(мм / шаг) * шаг));
}

function начальное() {
  const ст = конфиг.старт || {};
  const фасад = (конфиг.фасады || []).find((ф) => ф.id === ст.фасад) || (конфиг.фасады || [])[0];
  const столешница = (конфиг.столешницы || []).find((с) => с.id === ст.столешница)
    || (конфиг.столешницы || [])[0];
  const техника = { hob: false, oven: false };
  for (const т of ст.техника || []) if (т in техника) техника[т] = true;
  const база = {
    фасад: фасад ? фасад.id : "",
    столешница: столешница ? столешница.id : "",
    длина: предел(Math.round((ст.длина || 3) * 1000)),
    техника,
    покраска: типПокраскиИз(ст.покраска),
    // сторона угла для Г-образной: слева/справа (ветка вдоль левой или правой стены)
    сторона_угла: "левая",
    // фартук: старт из конфига («нет»); пусто = фартука нет
    фартук: (конфиг.фартук && конфиг.фартук.старт) || "нет",
    цвет_фартука: "",
  };
  const изАдреса = изСтроки(new URLSearchParams(location.search).get("k"));
  if (изАдреса) return {...база, ...изАдреса};
  try {
    const изПамяти = изСтроки(localStorage.getItem(ПАМЯТЬ));
    if (изПамяти) return {...база, ...изПамяти};
  } catch (e) { /* приватный режим */ }
  return база;
}

